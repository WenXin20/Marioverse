public class WeatheringCopperScrewBlock extends ScrewBlock implements SimpleWaterloggedBlock, WeatheringCopper {
    public static final MapCodec<WeatheringCopperScrewBlock> CODEC = RecordCodecBuilder.mapCodec(
            instance -> instance.group(WeatheringCopper.WeatherState.CODEC.fieldOf("weathering_state")
                            .forGetter(ChangeOverTimeBlock::getAge), propertiesCodec())
                    .apply(instance, WeatheringCopperScrewBlock::new));
    private final WeatheringCopper.WeatherState weatherState;

    @NotNull
    @Override
    public MapCodec<WeatheringCopperScrewBlock> codec() {
        return CODEC;
    }

    public WeatheringCopperScrewBlock(WeatheringCopper.WeatherState weatherState, BlockBehaviour.Properties properties) {
        super(properties);
        this.weatherState = weatherState;
    }

    @Override
    protected void randomTick(BlockState state, ServerLevel serverWorld, BlockPos pos, RandomSource random) {
        this.changeOverTime(state, serverWorld, pos, random);
    }

    @Override
    protected boolean isRandomlyTicking(BlockState state) {
        return WeatheringCopper.getNext(state.getBlock()).isPresent();
    }

    @NotNull
    public WeatheringCopper.WeatherState getAge() {
        return this.weatherState;
    }
}